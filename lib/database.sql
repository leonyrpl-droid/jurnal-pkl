
-- TABEL SISWA
CREATE TABLE public.siswa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT NOT NULL,
  kelas TEXT NOT NULL,
  tempat_pkl TEXT NOT NULL,
  pembimbing TEXT NOT NULL,
  kode TEXT NOT NULL UNIQUE
    CHECK (char_length(kode) BETWEEN 6 AND 12)
);

-- TABEL JURNAL
CREATE TABLE public.jurnal (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  siswa_id BIGINT NOT NULL
    REFERENCES public.siswa(id) ON DELETE CASCADE,
  tanggal DATE NOT NULL,
  kegiatan TEXT NOT NULL
    CHECK (char_length(kegiatan) BETWEEN 30 AND 500),
  kompetensi TEXT NOT NULL
    CHECK (char_length(kompetensi) BETWEEN 3 AND 60),
  durasi_jam INTEGER NOT NULL
    CHECK (durasi_jam BETWEEN 1 AND 10),
  status TEXT NOT NULL DEFAULT 'diajukan'
    CHECK (status IN ('diajukan', 'disetujui', 'revisi')),
  catatan TEXT,
  dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT satu_jurnal_per_hari UNIQUE (siswa_id, tanggal)
);

-- AKTIFKAN RLS
ALTER TABLE public.siswa ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.jurnal ENABLE ROW LEVEL SECURITY;
